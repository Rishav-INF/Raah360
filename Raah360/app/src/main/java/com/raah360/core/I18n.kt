package com.raah360.core

/** App languages. [tag] is the BCP-47 tag used for the screen and the voice (text-to-speech). */
enum class Lang(val tag: String, val nativeName: String, val englishName: String) {
    EN("en-IN", "English", "English"),
    HI("hi-IN", "हिन्दी", "Hindi"),
    KN("kn-IN", "ಕನ್ನಡ", "Kannada"),
    PA("pa-IN", "ਪੰਜਾਬੀ", "Punjabi"),
    TA("ta-IN", "தமிழ்", "Tamil"),
    TE("te-IN", "తెలుగు", "Telugu"),
    MR("mr-IN", "मराठी", "Marathi"),
    BN("bn-IN", "বাংলা", "Bengali");

    companion object {
        fun of(tag: String?): Lang = entries.firstOrNull { it.tag == tag } ?: EN
    }
}

/**
 * Every phrase the visitor sees or hears, per language. Templates use `{name}` placeholders;
 * place names (Room A, …) are passed through untranslated. Missing keys fall back to English.
 * Translations are a first pass: have a native speaker check each language before release.
 */
object I18n {
    fun t(lang: Lang, key: String, vararg args: Pair<String, Any>): String {
        var s = TABLES[lang]?.get(key) ?: EN[key] ?: key
        for ((k, v) in args) s = s.replace("{$k}", v.toString())
        return s
    }

    /** Category chip label for a place category ("Room", "Exit", …). */
    fun category(lang: Lang, category: String) = t(lang, "cat_" + category.lowercase())

